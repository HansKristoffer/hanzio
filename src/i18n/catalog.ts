const I18NEXT_PLURAL_SUFFIX = /_(zero|one|two|few|many|other)$/

/**
 * Validates one parsed JSON catalog: every leaf a string, no empty or dotted
 * key segments, NFC-normalized text and no mojibake.
 */
export function parseMessages(
	value: unknown,
	catalog: string,
	locale: string
): { messages?: Messages; issues: CatalogIssue[] } {
	const issues: CatalogIssue[] = []
	const issue = (message: string) => issues.push({ catalog, locale, message })

	function visit(node: unknown, path: string): string | Messages | undefined {
		if (typeof node === 'string') {
			if (node.normalize('NFC') !== node) {
				issue(`"${path}" is not Unicode NFC-normalized`)
			}
			if (MOJIBAKE.test(node)) issue(`"${path}" contains likely mojibake`)
			return node
		}
		if (!isPlainObject(node)) {
			issue(`"${path || '<root>'}" must be an object or string`)
			return undefined
		}
		const result: Record<string, string | Messages> = {}
		for (const [key, child] of Object.entries(node)) {
			if (!key || key.includes('.')) {
				issue(`"${path ? `${path}.` : ''}${key}" has an invalid key segment`)
				continue
			}
			const parsed = visit(child, path ? `${path}.${key}` : key)
			if (parsed !== undefined) result[key] = parsed
		}
		return result
	}

	const messages = visit(value, '')
	return {
		messages: typeof messages === 'object' ? messages : undefined,
		issues
	}
}

export function flattenCatalog(messages: Messages): Map<string, string> {
	return new Map(Object.entries(flattenMessages(messages)))
}

const quote = (value: string) =>
	`'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`

/**
 * The TypeScript key → placeholder-name map for `TypedTranslate`, generated
 * from the base catalog. Plural messages also take `count`: vue-i18n's
 * `a | b | c` forms, and i18next's `key_one`/`key_other` (merged into `key`).
 */
export function generateCatalogTypes(
	catalog: Pick<CatalogConfig, 'runtime' | 'generatedTypeName'>,
	baseMessages: Messages,
	command = 'hanzio-i18n generate'
): string {
	const entries = new Map<string, Set<string>>()

	for (const [rawKey, template] of flattenCatalog(baseMessages)) {
		const isI18nextPlural =
			catalog.runtime === 'i18next' && I18NEXT_PLURAL_SUFFIX.test(rawKey)
		const key = isI18nextPlural
			? rawKey.replace(I18NEXT_PLURAL_SUFFIX, '')
			: rawKey
		const params = entries.get(key) ?? new Set<string>()
		for (const name of extractPlaceholders(template)) params.add(name)
		const isVuePlural =
			catalog.runtime === 'vue-i18n' &&
			template
				.split('|')
				.map((part) => part.trim())
				.filter(Boolean).length > 1
		if (isVuePlural || isI18nextPlural) params.add('count')
		entries.set(key, params)
	}

	const lines = [...entries]
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([key, params]) => {
			const value =
				params.size === 0 ? 'never' : [...params].sort().map(quote).join(' | ')
			return `\t${quote(key)}: ${value}`
		})

	return [
		'/**',
		` * Generated by \`${command}\` from the base catalog.`,
		' * Do not edit by hand.',
		' */',
		`export type ${catalog.generatedTypeName ?? 'TranslationParams'} = {`,
		...lines,
		'}',
		''
	].join('\n')
}
