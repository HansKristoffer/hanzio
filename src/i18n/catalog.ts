import { isPlainObject } from '../guard'
import { extractPlaceholders, flattenMessages, type Messages } from '.'

/** How a catalog's runtime reads its messages: plural syntax and escaping. */
export type CatalogRuntime = 'vue-i18n' | 'i18next' | 'plain'

export type CatalogConfig = {
	/** Shown in check output. */
	name: string
	/** Folder of `<locale>.json` files, relative to the config file. */
	dir: string
	runtime: CatalogRuntime
	/** Where `hanzio-i18n generate` writes the key → placeholder map. */
	generatedTypes?: string
	/** Exported type name in `generatedTypes`. Default `TranslationParams`. */
	generatedTypeName?: string
	/**
	 * Source folders scanned for key references. Set them and the check also
	 * fails on keys nothing references. Leave unset when keys are built at
	 * runtime from a prefix (`t(\`widget.${key}\`)` everywhere), since every key
	 * would read as used.
	 */
	sourceRoots?: readonly string[]
	/**
	 * Key prefixes composed from data rather than written in source (labels
	 * sent by the backend, for example), kept even when nothing references them.
	 * A prefix a template literal spells out is found by the scan already.
	 */
	dynamicKeyPrefixes?: readonly string[]
}

export type CatalogIssue = {
	catalog: string
	locale?: string
	message: string
}

